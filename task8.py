season = {
    1: "Зима", 2: "Зима", 12: "Зима",
    3: "Весна", 4: "Весна", 5: "Весна",
    6: "Лето", 7: "Лето", 8: "Лето",
    9: "Осень", 10: "Осень", 11: "Осень",
}

while True:
    month = int(input("Введите номер месяца (от 1 до 12): "))

    if month in season:
        print(season[month])
        break
    else:
        print("Введите число от 1 до 12")

